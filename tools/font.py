"""font.py: the English VWF font (docs/re/text.md §English font).

fonts/vwf.txt glyphs go into the game's 12x16 font cells (4bpp TIM, 21 cells per 32-code row, code = 0xA0 + row*0x20
+ col). Codes: space = 00A0 (blank cell), digits and A-Z keep the full-width digit/letter cells (00A1-00CF), every
other glyph takes the hiragana cells from 00E0 on. Every other cell (katakana, ○×△□, 「」♪ ...) keeps its Japanese
glyph and a 12 px advance. The EXE hook (asm/vwf.asm) reads one advance byte per code 0xA0..0x1F4.

    python -X utf8 tools/font.py           # writes tbl/en.tbl, self-test
    python -X utf8 tools/font.py --sheet OUT.png   # the patched font as a cell sheet (fontsheet.py)
Used by build.py: widths() -> bytes, patch_tim(bytes) -> bytes.
"""
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import make_tbl  # noqa: E402

FONT = ROOT / "fonts" / "vwf.txt"
FIRST, LAST = 0xA0, 0x1F4  # codes the width table covers
TOP = 3  # glyph row 0 goes to cell row 3 (cap top); baseline = cell row 12
INK = 15  # CLUT index 15 = white (0x7fff), as the Japanese glyphs
SHADOW = 1  # CLUT index 1 = near black (0x8842)
MAXW = 11  # a glyph wider than the 12 px quad minus 1 would be cut
re_ctrl = re.compile(r"\{[^}]*\}")


def load_font(path=FONT):
    """-> {char: (rows, advance)}; rows = list of strings of '#'/'.'."""
    glyphs, cur = {}, None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("#") and not set(line) <= {"#", "."}:
            continue
        if line.startswith("== "):
            parts = line[3:].split(" ")
            ch = " " if parts[0] == "space" else parts[0]
            cur = glyphs[ch] = [[], int(parts[1]) if len(parts) > 1 else None]
        elif line and cur is not None:
            cur[0].append(line)
    out = {}
    for ch, (rows, adv) in glyphs.items():
        w = max((len(r) for r in rows), default=0)
        ink = max((r.rfind("#") + 1 for r in rows), default=0)
        out[ch] = (rows, adv if adv is not None else ink + 1)
        assert len(rows) <= 12 and w <= MAXW, (ch, len(rows), w)
    return out


def codes(glyphs):
    """char -> glyph code."""
    m = {" ": 0xA0}
    for i, c in enumerate("0123456789ABCDEFGHIJ"):
        m[c] = 0xA1 + i
    for i, c in enumerate("KLMNOPQRSTUVWXYZ"):
        m[c] = 0xC0 + i
    free = [0xA0 + r * 0x20 + c for r in range(2, 5) for c in range(21)]  # hiragana rows 2-4
    rest = [c for c in glyphs if c not in m]
    assert len(rest) <= len(free), len(rest)
    m.update(zip(rest, free))
    return m


def widths(glyphs=None):
    glyphs = glyphs or load_font()
    w = bytearray([12] * (LAST - FIRST + 1))
    for ch, code in codes(glyphs).items():
        w[code - FIRST] = glyphs[ch][1]
    return bytes(w)


def patch_tim(tim, glyphs=None):
    """Font TIM (4bpp, CLUT, 256x256 px image at VRAM 960,0) -> the same TIM with the English cells drawn."""
    glyphs = glyphs or load_font()
    d = bytearray(tim)
    clen = struct.unpack_from("<I", d, 8)[0]
    o = 8 + clen
    _, _, _, w16, h = struct.unpack_from("<IHHHH", d, o)
    pix, stride = o + 12, w16 * 2
    assert (w16 * 4, h) == (256, 256)

    def put(x, y, v):
        i = pix + y * stride + x // 2
        d[i] = (d[i] & 0xF0) | v if x % 2 == 0 else (d[i] & 0x0F) | (v << 4)

    for ch, code in codes(glyphs).items():
        u, v = (code & 31) * 12, (code >> 5) * 16
        for y in range(16):
            for x in range(12):
                put(u + x, v + y, 0)
        ink = {(x, y) for y, row in enumerate(glyphs[ch][0]) for x, c in enumerate(row) if c == "#"}
        for x, y in ink:  # shadow right, down and down-right (stays inside the advance column and the cell)
            for dx, dy in ((1, 0), (0, 1), (1, 1)):
                if (x + dx, y + dy) not in ink and x + dx < 12 and TOP + y + dy < 16:
                    put(u + x + dx, v + TOP + y + dy, SHADOW)
        for x, y in ink:
            put(u + x, v + TOP + y, INK)
    return bytes(d)


def line_px(line, glyphs=None):
    """Pixel width of one line of `en` text (control codes {..} take no space; the shadow column is in the advance).
    Characters without an English glyph are Japanese cells: 12 px."""
    glyphs = glyphs or _GLYPHS()
    line = re_ctrl.sub("", line)
    return sum(glyphs[c][1] if c in glyphs else 12 for c in line)


def _GLYPHS(cache={}):
    if "g" not in cache:
        cache["g"] = load_font()
    return cache["g"]


def write_tbl(glyphs=None):
    """tbl/en.tbl: the English glyphs, the Japanese cells left untouched, and the control codes."""
    glyphs = glyphs or load_font()
    m = codes(glyphs)
    used = set(m.values())
    lines = ["# generated by tools/font.py: do not edit by hand"]
    lines += [f"{code:04X}={'\\s' if ch == ' ' else ch}" for ch, code in sorted(m.items(), key=lambda x: x[1])]
    lines += [f"{code:04X}={ch}" for code, ch in make_tbl.entries() if code not in used]
    lines += ["81={sp81}", "82={n}", "85={col:1}", "FF={end}"]
    out = ROOT / "tbl" / "en.tbl"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return out


def selftest():
    g = load_font()
    m = codes(g)
    for c in map(chr, range(0x20, 0x7F)):
        if c not in "\\^`{|}$":
            assert c in m, f"no glyph for {c!r}"
    assert all(FIRST <= v <= LAST and (v & 31) < 21 for v in m.values())
    w = widths(g)
    assert w[0] == 4 and w[m["M"] - FIRST] == 8, (w[0], w[m["M"] - FIRST])
    assert 0 not in w


if __name__ == "__main__":
    selftest()
    print(write_tbl())
    if "--sheet" in sys.argv:
        import subprocess
        tmp = ROOT / "work" / "font_en.bin"
        tmp.write_bytes(patch_tim((ROOT / "work" / "pac" / "CARDMS.PAC" / "1.bin").read_bytes()))
        subprocess.run([sys.executable, "-X", "utf8", str(ROOT / "tools" / "fontsheet.py"), str(tmp),
                        sys.argv[sys.argv.index("--sheet") + 1]], check=True)
