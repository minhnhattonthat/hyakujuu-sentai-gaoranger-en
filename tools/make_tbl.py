"""make_tbl.py: write tbl/jp.tbl from the font sheet layout (CARDMS.PAC/1, a 4bpp TIM of 12x12 cells, 21 per row).

Glyph code = 0x00A0 + row * 0x20 + col, stored big-endian (00A0..01F4). `_` = empty cell (no entry).
Control bytes: 82 = newline, FF = end (docs/re/text.md). Run: python -X utf8 tools/make_tbl.py"""
from pathlib import Path

ROWS = [
    "　0123456789ABCDEFGHIJ",  # col 0 = full-width space
    "KLMNOPQRSTUVWXYZ_○×△□",
    "ぁあぃいぅうぇえぉおかがきぎくぐけげこごさ",
    "ざしじすずせぜそぞただちぢっつづてでとどな",
    "にぬねのはぱばひぴびふぷぶへぺべほぽぼまみ",  # handakuten before dakuten (checked on the cell sheet)
    "むめもゃやゅゆょよらりるれろゎわをんァアィ",
    "イゥウェエォオカガキギクグケゲコゴサザシジ",
    "スズセゼソゾタダチヂッツヅテデトドナニヌネ",
    "ノハパバヒピビフプブヘペベホポボマミムメモ",
    "ャヤュユョヨラリルレロヮワヲンヴヵヶ々ー_",
    "。、？！・…〜”（）「」♪__方向上下左右",
]
# 81: 1-byte space (between ○ choices, mid-sentence); 85 xx: colour/attribute (guess), 1 argument byte
CTRL = ["81=\\s", "82={n}", "85={col:1}", "FF={end}"]


def entries():
    for r, row in enumerate(ROWS):
        assert len(row) == 21, (r, len(row), row)
        for c, ch in enumerate(row):
            if ch != "_":
                yield 0xA0 + r * 0x20 + c, ch


if __name__ == "__main__":
    lines = ["# generated by tools/make_tbl.py: do not edit by hand"]
    lines += [f"{code:04X}={ch}" for code, ch in entries()] + CTRL
    out = Path(__file__).resolve().parents[1] / "tbl" / "jp.tbl"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(out, len(lines) - 1, "entries")
