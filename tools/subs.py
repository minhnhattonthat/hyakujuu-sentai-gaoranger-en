"""subs.py: in-game voice subtitles (CDXA clips) -> build/subs_data.asm for asm/subs.asm (docs/re/fmv.md §In-game voice).

script/subs.tsv rows whose src is CDXA0<n>_c<ch> (n = XA/CDXA0<n>.XA, ch = XA channel) are spoken lines the engine
shows while that channel plays. start/end are seconds of that channel's own audio (the timeline tools/xawav.py +
tools/asr.py give: the channel's audio sectors back to back). The CDXA files interleave 16 channels with null
sectors where a channel is silent, so a time maps to a file sector through the channel's list of audio sectors; the
engine compares that with the LBA the XA driver last read (gp+0x2a8) minus the file's LBA.

Text: the English VWF font (fonts/vwf.txt, ASCII 0x20-0x7E), auto-wrapped to <= 2 lines of LINE_PX; '|' forces a
break. lint() reports rows that don't fit.

    python -X utf8 tools/subs.py [--asm build/subs_data.asm]    # writes the asm, prints the row count and lint
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import font  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SUBS = ROOT / "script" / "subs.tsv"
XA = ROOT / "work" / "disc" / "tree" / "XA"
SECTOR_S = 4032 / 37800  # one XA sector: 4032 samples, mono 37.8 kHz (coding byte 0x00 in every CDXA sector)
CANVAS_PX = 304  # asm/subs.asm canvas width; 1 px outline each side
LINE_PX = CANVAS_PX - 2
FIRST, LAST = 0x20, 0x7E
ROWS = 12  # glyph rows (fonts/vwf.txt)


def channel_sectors(n):
    """{channel: [file sector index of each audio sector of that channel, in order]} for XA/CDXA0<n>.XA."""
    d = (XA / f"CDXA0{n}.XA").read_bytes()
    out = {}
    for i in range(len(d) // 2336):
        fn, ch, sub = d[i * 2336], d[i * 2336 + 1], d[i * 2336 + 2]
        if sub & 0x04 and fn == 1:  # audio sector of this file
            out.setdefault(ch, []).append(i)
    return out


def load_rows():
    """[(file n, channel, start s, end s, ja, en)] CDXA rows of script/subs.tsv that have English."""
    rows = []
    for line in SUBS.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        src, start, end, ja, en = (line.split("\t") + [""] * 5)[:5]
        if src.startswith("CDXA") and en.strip():
            n, ch = src[4:].split("_c")
            rows.append((int(n), int(ch), float(start), float(end), ja, en.strip()))
    return rows


def wrap(text, glyphs):
    lines = []
    for part in text.split("|"):
        cur = ""
        for w in part.split():
            t = f"{cur} {w}".strip()
            if cur and font.line_px(t, glyphs) > LINE_PX:
                lines.append(cur)
                t = w
            cur = t
        lines.append(cur)
    return lines


def lint(rows=None, glyphs=None):
    glyphs = glyphs or font.load_font()
    errs = []
    for n, ch, t0, t1, ja, en in rows if rows is not None else load_rows():
        bad = sorted({c for c in en.replace("|", "") if c not in glyphs or not FIRST <= ord(c) <= LAST})
        lines = wrap(en, glyphs)
        if bad:
            errs.append(f"subs CDXA0{n}_c{ch} {t0}: characters not in the font {bad}: {en}")
        if len(lines) > 2 or any(font.line_px(x, glyphs) > LINE_PX for x in lines):
            errs.append(f"subs CDXA0{n}_c{ch} {t0}: more than 2 lines of {LINE_PX} px: {lines}")
        if t1 <= t0:
            errs.append(f"subs CDXA0{n}_c{ch} {t0}: end {t1} <= start")
    return errs


def table(rows=None):
    """[(file n, channel, first sector, end sector, [lines])], sectors relative to the start of XA/CDXA0<n>.XA."""
    glyphs = font.load_font()
    rows = load_rows() if rows is None else rows
    maps = {n: channel_sectors(n) for n in sorted({r[0] for r in rows})}
    out = []
    for n, ch, t0, t1, _ja, en in rows:
        secs = maps[n][ch]
        # +2 sectors (~0.2 s) past a mid-channel start: a clip's last sector can hold the next line's first words,
        # which flashed that line for a few frames at the clip's end
        a = secs[min(int(t0 / SECTOR_S) + (2 if t0 > 0 else 0), len(secs) - 1)]
        i1 = int(t1 / SECTOR_S)
        b = secs[i1] if i1 < len(secs) else secs[-1] + 16
        out.append((n, ch, a, b, wrap(en, glyphs)))
    return out


def asm(rows=None):
    glyphs = font.load_font()
    q = glyphs["?"]
    lines = ["; generated by tools/subs.py from fonts/vwf.txt and script/subs.tsv: do not edit", ".align 4",
             "SubAdv:"]
    adv, bits = [], []
    for c in range(FIRST, LAST + 1):
        g = glyphs.get(chr(c), q)
        adv.append(g[1])
        rows_ = g[0] + ["."] * (ROWS - len(g[0]))
        bits += [sum(1 << x for x, p in enumerate(r) if p == "#") for r in rows_]
    for i in range(0, len(adv), 16):
        lines.append("  .byte " + ", ".join(str(a) for a in adv[i:i + 16]))
    lines += [".align 2", "SubRows:"]
    for i in range(0, len(bits), 12):
        lines.append("  .halfword " + ", ".join(f"0x{b:04x}" for b in bits[i:i + 12]))
    tab = table(rows)
    lines += [".align 4", "SubTable:  ; u8 file, u8 channel, u16 0, u16 first sector, u16 end sector, u32 text"]
    for i, (n, ch, a, b, _) in enumerate(tab):
        lines.append(f"  .byte {n}, {ch}\n  .halfword 0, {a}, {b}\n  .word SubText{i}")
    lines.append("  .byte 0xFF, 0xFF\n  .halfword 0, 0, 0\n  .word 0")
    for i, (*_, ls) in enumerate(tab):
        data = "\n".join(ls).encode("ascii") + b"\0"
        lines.append(f"SubText{i}:  ; {' / '.join(ls)}")
        lines.append("  .byte " + ", ".join(str(x) for x in data))
    return "\n".join(lines) + "\n.align 4\n"


def selftest():
    secs = channel_sectors(0)
    assert all(len(v) > 100 for v in secs.values()), "CDXA00: every channel has audio"
    assert secs[13][0] == 13 and secs[13][1] == 29, "16-channel interleave"
    t = table([(0, 13, 0.0, 1.0, "", "Test line")])
    assert t[0][:4] == (0, 13, 13, secs[13][int(1.0 / SECTOR_S)]), t
    assert lint([(0, 0, 0.0, 1.0, "", "W" * 60)]), "an over-long row is reported"
    assert not lint([(0, 0, 0.0, 1.0, "", "Short line|second line")])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--asm", default=str(ROOT / "build" / "subs_data.asm"))
    a = ap.parse_args()
    selftest()
    rows = load_rows()
    Path(a.asm).parent.mkdir(parents=True, exist_ok=True)
    Path(a.asm).write_text(asm(rows), encoding="ascii")
    errs = lint(rows)
    for e in errs:
        print(e)
    print(f"{len(rows)} in-game subtitle rows -> {a.asm}")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
